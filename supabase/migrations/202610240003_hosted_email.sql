create table public.outreach_locks (key text primary key, owner uuid not null, expires timestamptz not null);
create table public.outreach_mail_state (key text primary key, last_uid bigint not null default 0 check(last_uid>=0));
create table public.outreach_intakes (message_key text primary key, sender text not null, subject text not null, received_at timestamptz not null, analysis jsonb not null, created_at timestamptz not null default now());
create table public.outreach_leads (
  id bigint generated by default as identity primary key, domain text not null unique, business text not null,
  website text not null, email text not null unique check(email=lower(email)), contact_source text not null,
  fact text not null, fact_quote text not null, country_evidence text not null, sources text not null,
  verified_at timestamptz not null, ecommerce_verified boolean not null default false, product_url text, ecommerce_evidence text,
  status text not null default 'queued' check(status in ('queued','draft','sending','sent','replied','suppressed','uncertain')),
  subject text, body text, message_id text unique, sent_at timestamptz, error text,
  check(not ecommerce_verified or (product_url like 'https://%' and length(ecommerce_evidence)>10))
);
create table public.outreach_suppressions (email text primary key check(email=lower(email)), reason text not null, created_at timestamptz not null default now());
create table public.outreach_settings (key text primary key, value text not null);
create table public.outreach_candidates (id bigint generated always as identity primary key, name text not null, website text not null, domain text not null unique, status text not null default 'pending' check(status in ('pending','processing','verified','skipped')), claimed_at timestamptz);
create index outreach_leads_status on public.outreach_leads(status,id);
create index outreach_leads_sent_at on public.outreach_leads(sent_at) where sent_at is not null;
insert into public.outreach_settings values ('delivery_enabled','false'),('migration_complete','false'),('inbox_pending','true');

create function public.orit_claim(p_key text,p_owner uuid,p_seconds integer default 180) returns boolean
language plpgsql security definer set search_path='' as $$
declare n integer;
begin
  insert into public.outreach_locks values(p_key,p_owner,now()+make_interval(secs=>least(greatest(p_seconds,10),600)))
    on conflict(key) do update set owner=excluded.owner,expires=excluded.expires where public.outreach_locks.expires<now();
  get diagnostics n=row_count; return n=1;
end $$;
create function public.orit_release(p_key text,p_owner uuid) returns void language sql security definer set search_path='' as $$ delete from public.outreach_locks where key=p_key and owner=p_owner $$;
create function public.orit_advance(p_key text,p_uid bigint) returns void language sql security definer set search_path='' as $$
  insert into public.outreach_mail_state values(p_key,p_uid) on conflict(key) do update set last_uid=greatest(public.outreach_mail_state.last_uid,excluded.last_uid)
$$;
create function public.orit_suppress(p_email text,p_reason text,p_reply boolean default false) returns void language plpgsql security definer set search_path='' as $$
begin
  perform pg_catalog.pg_advisory_xact_lock(884023101);
  insert into public.outreach_suppressions(email,reason) values(lower(p_email),p_reason) on conflict(email) do nothing;
  update public.outreach_leads set status=case when p_reply then 'replied' else 'suppressed' end
    where email=lower(p_email) and status in ('queued','draft','sending','uncertain',case when p_reply then 'sent' else 'queued' end);
end $$;
create function public.orit_reserve(p_id bigint,p_message_id text,p_daily_limit integer,p_spacing_ms integer) returns boolean
language plpgsql security definer set search_path='' as $$
declare n integer; cap integer;
begin
  perform pg_catalog.pg_advisory_xact_lock(884023101);
  if not exists(select 1 from public.outreach_settings where key='delivery_enabled' and value='true') then return false; end if;
  if not exists(select 1 from public.outreach_settings where key='migration_complete' and value='true') then return false; end if;
  if exists(select 1 from public.outreach_settings where key='inbox_pending' and value<>'false') then return false; end if;
  if not exists(select 1 from public.outreach_settings where key='inbox_caught_up_at' and value::timestamptz>now()-interval '10 minutes') then return false; end if;
  cap=least(greatest(p_daily_limit,1),20);
  if (select count(*) from public.outreach_leads where sent_at>now()-interval '24 hours')>=cap then return false; end if;
  if exists(select 1 from public.outreach_leads where status in ('sending','uncertain')) then return false; end if;
  if exists(select 1 from public.outreach_leads where sent_at>now()-make_interval(secs=>greatest(p_spacing_ms,300000)/1000.0)) then return false; end if;
  update public.outreach_leads set status='sending',message_id=p_message_id,sent_at=now()
    where id=p_id and status='draft' and ecommerce_verified and product_url is not null
      and verified_at>now()-interval '7 days' and subject is not null and body is not null
      and not exists(select 1 from public.outreach_suppressions where email=public.outreach_leads.email);
  get diagnostics n=row_count;return n=1;
end $$;
create function public.orit_candidate() returns jsonb language plpgsql security definer set search_path='' as $$
declare row public.outreach_candidates;
begin
  select * into row from public.outreach_candidates where status='pending' or (status='processing' and claimed_at<now()-interval '10 minutes') order by id limit 1 for update skip locked;
  if row.id is null then return null; end if;
  update public.outreach_candidates set status='processing',claimed_at=now() where id=row.id;
  return jsonb_build_object('id',row.id,'website',row.website);
end $$;
create function public.orit_summary() returns jsonb language sql security definer set search_path='' as $$
  select coalesce(jsonb_agg(row),'[]'::jsonb) from (select status,count(*) as count from public.outreach_leads group by status) row
$$;

-- Runtime credentials stay in Vault, separate from source and public tables.
create function public.orit_runtime_secrets() returns jsonb language sql security definer set search_path='' as $$
  select coalesce(jsonb_object_agg(substring(name from 15),decrypted_secret),'{}'::jsonb)
    from vault.decrypted_secrets where name like 'orit_outreach_%'
$$;
create function public.orit_configure(p_values jsonb) returns void language plpgsql security definer set search_path='' as $$
declare item record; secret_id uuid;
begin
  for item in select key,value from jsonb_each_text(p_values) loop
    if item.key not in ('OPENAI_API_KEY','GMAIL_APP_PASSWORD','GMAIL_USER','OUTREACH_POSTAL_ADDRESS','EMAIL_START_DATE','OUTREACH_DAILY_LIMIT','OUTREACH_FOCUS','OPENAI_EMAIL_MODEL','OPENAI_DISCOVERY_MODEL') then raise exception 'Unsupported runtime setting'; end if;
    select id into secret_id from vault.secrets where name='orit_outreach_'||item.key;
    if secret_id is null then perform vault.create_secret(item.value,'orit_outreach_'||item.key);
    else perform vault.update_secret(secret_id,item.value); end if;
  end loop;
end $$;

-- Import preserves all prior sends and opt-outs before cloud delivery can be enabled.
create function public.orit_import(p_snapshot jsonb) returns jsonb language plpgsql security definer set search_path='' as $$
declare item jsonb;
begin
  if exists(select 1 from public.outreach_settings where key='migration_complete' and value='true') then raise exception 'Snapshot already imported'; end if;
  for item in select value from jsonb_array_elements(coalesce(p_snapshot->'leads','[]')) loop
    insert into public.outreach_leads(domain,business,website,email,contact_source,fact,fact_quote,country_evidence,sources,verified_at,status,subject,body,message_id,sent_at,error,ecommerce_verified)
    values(item->>'domain',item->>'business',item->>'website',lower(item->>'email'),item->>'contact_source',item->>'fact',item->>'fact_quote',item->>'country_evidence',item->>'sources',(item->>'verified_at')::timestamptz,item->>'status',item->>'subject',item->>'body',item->>'message_id',(item->>'sent_at')::timestamptz,item->>'error',false)
    on conflict do nothing;
  end loop;
  for item in select value from jsonb_array_elements(coalesce(p_snapshot->'intakes','[]')) loop
    insert into public.outreach_intakes values(item->>'message_key',item->>'sender',item->>'subject',(item->>'received_at')::timestamptz,(item->>'analysis')::jsonb,(item->>'created_at')::timestamptz) on conflict do nothing;
  end loop;
  for item in select value from jsonb_array_elements(coalesce(p_snapshot->'suppressions','[]')) loop
    insert into public.outreach_suppressions values(lower(item->>'email'),item->>'reason',(item->>'created_at')::timestamptz) on conflict do nothing;
  end loop;
  for item in select value from jsonb_array_elements(coalesce(p_snapshot->'mail_state','[]')) loop
    perform public.orit_advance(item->>'key',(item->>'last_uid')::bigint);
  end loop;
  insert into public.outreach_settings values('migration_complete','true') on conflict(key) do update set value='true';
  return jsonb_build_object('leads',(select count(*) from public.outreach_leads),'intakes',(select count(*) from public.outreach_intakes),'suppressions',(select count(*) from public.outreach_suppressions));
end $$;

do $$ declare table_name text; function_row record;
begin
  foreach table_name in array array['outreach_locks','outreach_mail_state','outreach_intakes','outreach_leads','outreach_suppressions','outreach_settings','outreach_candidates'] loop
    execute format('alter table public.%I enable row level security',table_name);
    execute format('revoke all on public.%I from anon, authenticated',table_name);
    execute format('grant all on public.%I to service_role',table_name);
  end loop;
  for function_row in select p.oid::regprocedure as signature from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.proname like 'orit_%' loop
    execute format('revoke all on function %s from public, anon, authenticated',function_row.signature);
    execute format('grant execute on function %s to service_role',function_row.signature);
  end loop;
end $$;
