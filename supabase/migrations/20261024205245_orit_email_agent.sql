-- 20261024204812_outreach_research_handoff.sql
-- The local worker links each saved Gmail intake to at most one research run.
-- This is intentionally separate from the model's unverified order_reference.
alter table public.outreach_intakes
  add column research_status text not null default 'pending'
    check (research_status in ('pending', 'processing', 'linked', 'needs_details', 'skipped', 'failed')),
  add column research_owner_id uuid,
  add column research_project_id uuid,
  add column research_run_id uuid,
  add column research_claim_token uuid,
  add column research_claimed_at timestamptz,
  add column research_attempts integer not null default 0 check (research_attempts >= 0),
  add column research_next_attempt_at timestamptz not null default now(),
  add column research_error text,
  add column research_started_at timestamptz,
  add constraint outreach_intakes_research_project_fk
    foreign key (research_project_id, research_owner_id)
    references public.projects(id, owner_id),
  add constraint outreach_intakes_research_run_fk
    foreign key (research_run_id, research_owner_id)
    references public.runs(id, owner_id),
  add constraint outreach_intakes_linked_has_run
    check (research_status <> 'linked' or
      (research_owner_id is not null and research_project_id is not null and research_run_id is not null));

create unique index outreach_intakes_research_run_uniq
  on public.outreach_intakes(research_run_id) where research_run_id is not null;
create index outreach_intakes_research_pending_idx
  on public.outreach_intakes(research_next_attempt_at, received_at)
  where research_status = 'pending';
create index outreach_intakes_research_processing_idx
  on public.outreach_intakes(research_claimed_at)
  where research_status = 'processing';

-- A claim is committed before creating the project. The project/run idempotency
-- key is derived from message_key, so a crash after run creation can be retried.
create function public.orit_claim_research_intake(p_token uuid)
returns public.outreach_intakes
language plpgsql security definer set search_path = '' as $$
declare claimed public.outreach_intakes;
begin
  select * into claimed from public.outreach_intakes
    where research_attempts < 3
      and research_next_attempt_at <= now()
      and (research_status = 'pending' or
        (research_status = 'processing' and research_claimed_at < now() - interval '5 minutes'))
    order by received_at, message_key
    for update skip locked limit 1;
  if claimed.message_key is null then return null; end if;
  update public.outreach_intakes
    set research_status = 'processing', research_claim_token = p_token,
        research_claimed_at = now(), research_attempts = research_attempts + 1
    where message_key = claimed.message_key
    returning * into claimed;
  return claimed;
end $$;
revoke all on function public.orit_claim_research_intake(uuid) from public, anon, authenticated;
grant execute on function public.orit_claim_research_intake(uuid) to service_role;
